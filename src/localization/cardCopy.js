export function localizeCardRecord(namespace, slug, record, t) {
  if (!record) return record;
  const localized = Object.fromEntries(Object.entries(record).map(([field, value]) => {
    const key = `cards.${namespace}.${slug}.${field}`;
    return [field, key in en ? t(key) : value];
  }));
  for (const field of ["name", "hostName"]) {
    const key = `cards.${namespace}.${slug}.${field}Possessive`;
    if (key in en) localized[`${field}Possessive`] = t(key);
  }
  return localized;
}

